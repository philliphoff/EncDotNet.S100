using EncDotNet.S100.Interoperability;
using EncDotNet.S100.Pipelines;
using EncDotNet.S100.Pipelines.Coverage;
using EncDotNet.S100.Portrayals.Application;

namespace EncDotNet.S100.Datasets.Weather;

/// <summary>
/// How a weather layer is drawn from a <see cref="WeatherCoverageSource"/>:
/// either a colour fill (<see cref="WeatherLayerKind.Fill"/>) or oriented
/// symbols (<see cref="WeatherLayerKind.Symbols"/>), with its S-98 display
/// plane, its priority within the plane, its opacity and whether it is shown
/// by default.
/// </summary>
/// <remarks>
/// <para>
/// GRIB2 and NetCDF-CF have no portrayal catalogue, so the weather styles are
/// SoundCharts' own, defined in code with the portrayal toolkit
/// (<see cref="WeatherPalette"/>, <see cref="Symbols"/>,
/// <see cref="ContentScope"/>). Being <see cref="ICoverageStyle"/>s, they go
/// through the ordinary coverage pipeline, and both renderers draw them with
/// no weather-specific code (design note weather-sources.md §4).
/// </para>
/// <list type="table">
///   <listheader><term>Style</term><description>Drawn as</description></listheader>
///   <item><term><see cref="WaveHeightStyle"/></term><description>A <c>wave.hs</c> fill. On by default.</description></item>
///   <item><term><see cref="WindBarbStyle"/></term><description>WMO wind barbs from <c>wind.speed</c> and <c>wind.from_direction</c>. On by default.</description></item>
///   <item><term><see cref="WindSpeedStyle"/></term><description>A <c>wind.speed</c> fill in Beaufort bands. Off by default.</description></item>
///   <item><term><see cref="WaveDirectionStyle"/></term><description>Arrows along <c>wave.dir</c>, sized by <c>wave.hs</c>. Off by default.</description></item>
/// </list>
/// <para>
/// Layer order (design note §5): fills go on
/// <see cref="S98DisplayPlane.OnDemandSurface"/> at priority
/// <see cref="FillPriority"/>, under the S-104 surface; barbs and arrows go on
/// <see cref="S98DisplayPlane.DynamicArrows"/> at priority
/// <see cref="SymbolPriority"/>, over the S-111 arrows (priority 10). The
/// sub-layers <see cref="WeatherPortrayal"/> builds carry these.
/// </para>
/// <para>
/// A style holds the active palette, so give each layer its own instance.
/// It is not meant for concurrent mutation.
/// </para>
/// </remarks>
public abstract class WeatherCoverageStyle : ICoverageStyle
{
    /// <summary>
    /// The version of the weather styles, folded into <see cref="ContentScope"/>.
    /// Bump it whenever the symbols, the palette or the bands change.
    /// </summary>
    public const int StyleVersion = 1;

    /// <summary>The opacity of the colour fills: 0.5, so the chart under them stays readable.</summary>
    public const double FillOpacity = 0.5;

    /// <summary>The fills' priority within <see cref="S98DisplayPlane.OnDemandSurface"/>: 0, under the S-104 surface.</summary>
    public const int FillPriority = 0;

    /// <summary>The barbs' and arrows' priority within <see cref="S98DisplayPlane.DynamicArrows"/>: 20, over the S-111 arrows (10).</summary>
    public const int SymbolPriority = 20;

    /// <summary>
    /// The weather symbols (wind barbs, the calm circle and the wave arrow),
    /// embedded from the project's <c>Symbols</c> folder. Colours are palette
    /// classes resolved against <see cref="WeatherPalette.Palette"/>.
    /// </summary>
    /// <remarks>
    /// The SVGs are generated by <c>tools/GenerateWeatherSymbols</c> and
    /// checked in. They follow the S-100 SVG conventions: sizes in
    /// millimetres (one user unit is one millimetre), the pivot point at the
    /// origin and the centre of the view box (the arrow renderers centre a
    /// symbol on its cell), and colours by palette class.
    /// </remarks>
    public static SymbolSet Symbols { get; } =
        new(typeof(WeatherCoverageStyle).Assembly, "EncDotNet.S100.Datasets.Weather.Symbols");

    /// <summary>
    /// The weather styles' part of the tile disk-cache content scope: the style
    /// name and <see cref="StyleVersion"/> plus the toolkit version
    /// (<see cref="ApplicationContentScope.For"/>).
    /// </summary>
    public static string ContentScope { get; } = ApplicationContentScope.For("Weather", StyleVersion);

    private PaletteType _activePaletteType = PaletteType.Day;

    /// <summary>Initialises a style.</summary>
    /// <param name="layerKey">The stable sub-layer key, e.g. <c>"weather.wave.height"</c>.</param>
    /// <param name="name">The layer's display name, e.g. <c>"Wave height"</c>.</param>
    /// <param name="kind">Whether it is a fill or symbols.</param>
    /// <param name="valueFieldName">The coverage field the bands are keyed on.</param>
    /// <param name="rotationFieldName">The field the symbols are rotated by; <see langword="null"/> for a fill.</param>
    /// <param name="isVisibleByDefault">Whether the layer is shown until the mariner hides it.</param>
    private protected WeatherCoverageStyle(
        string layerKey,
        string name,
        WeatherLayerKind kind,
        string valueFieldName,
        string? rotationFieldName,
        bool isVisibleByDefault)
    {
        LayerKey = layerKey;
        Name = name;
        Kind = kind;
        ValueFieldName = valueFieldName;
        RotationFieldName = rotationFieldName;
        IsVisibleByDefault = isVisibleByDefault;
    }

    /// <summary>The stable sub-layer key, e.g. <c>"weather.wave.height"</c>.</summary>
    public string LayerKey { get; }

    /// <summary>The layer's display name, e.g. <c>"Wave height"</c>.</summary>
    public string Name { get; }

    /// <summary>Whether the style draws a colour fill or oriented symbols.</summary>
    public WeatherLayerKind Kind { get; }

    /// <summary>The coverage field the bands are keyed on, e.g. <c>"wave.hs"</c>.</summary>
    public string ValueFieldName { get; }

    /// <summary>The field the symbols are rotated by, or <see langword="null"/> for a fill.</summary>
    public string? RotationFieldName { get; }

    /// <summary>Whether the layer is shown until the mariner hides it.</summary>
    public bool IsVisibleByDefault { get; }

    /// <summary>
    /// The S-98 display plane: <see cref="S98DisplayPlane.OnDemandSurface"/>
    /// for a fill, <see cref="S98DisplayPlane.DynamicArrows"/> for symbols.
    /// </summary>
    public S98DisplayPlane Plane => Kind == WeatherLayerKind.Fill
        ? S98DisplayPlane.OnDemandSurface
        : S98DisplayPlane.DynamicArrows;

    /// <summary>
    /// The priority within <see cref="Plane"/>: <see cref="FillPriority"/> for
    /// a fill, <see cref="SymbolPriority"/> for symbols.
    /// </summary>
    public int WithinPlanePriority => Kind == WeatherLayerKind.Fill ? FillPriority : SymbolPriority;

    /// <summary>
    /// The portrayal opacity: <see cref="FillOpacity"/> for a fill, 1 for
    /// symbols. Renderers multiply it with any user opacity.
    /// </summary>
    public double Opacity => Kind == WeatherLayerKind.Fill ? FillOpacity : 1.0;

    /// <summary>
    /// Gets the active colour palette: <see cref="WeatherPalette.Palette"/>'s
    /// colours for the palette last passed to <see cref="SwitchPaletteAsync"/>
    /// (Day until then).
    /// </summary>
    public ColorPalette ActivePalette => WeatherPalette.Palette.GetColorPalette(_activePaletteType);

    /// <summary>The palette last passed to <see cref="SwitchPaletteAsync"/>; Day until then.</summary>
    public PaletteType ActivePaletteType => _activePaletteType;

    /// <summary>Empty: no weather style draws contours yet (pressure isobars are later work).</summary>
    public IReadOnlyList<ContourStyle> Contours => [];

    /// <inheritdoc/>
    public ValueTask SwitchPaletteAsync(PaletteType type, CancellationToken cancellationToken = default)
    {
        _activePaletteType = type;
        return ValueTask.CompletedTask;
    }

    /// <summary>
    /// The colour bands of a fill, resolved against the active palette, or
    /// <see langword="null"/> for a symbol style.
    /// </summary>
    /// <param name="settings">Unused: the weather bands don't depend on mariner settings.</param>
    public virtual CoverageColorScheme? ResolveColorScheme(MarinerSettings settings) => null;

    /// <summary>The symbol bands of a symbol style, or <see langword="null"/> for a fill.</summary>
    /// <param name="settings">Unused: the weather bands don't depend on mariner settings.</param>
    public virtual CoverageSymbolScheme? ResolveSymbolScheme(MarinerSettings settings) => null;

    /// <summary>
    /// Whether <paramref name="source"/> carries the fields this style reads
    /// (<see cref="ValueFieldName"/> and, for symbols, <see cref="RotationFieldName"/>),
    /// stored or derived.
    /// </summary>
    /// <param name="source">The coverage source.</param>
    public bool AppliesTo(WeatherCoverageSource source)
    {
        ArgumentNullException.ThrowIfNull(source);
        return source.FieldNames.Contains(ValueFieldName, StringComparer.Ordinal)
            && (RotationFieldName is null || source.FieldNames.Contains(RotationFieldName, StringComparer.Ordinal));
    }

    /// <summary>
    /// New instances of every weather style, in layer-stack order: the wave
    /// height and wind speed fills, then the wind barbs and wave arrows.
    /// </summary>
    public static IReadOnlyList<WeatherCoverageStyle> CreateAll() =>
        [new WaveHeightStyle(), new WindSpeedStyle(), new WindBarbStyle(), new WaveDirectionStyle()];

    /// <summary>
    /// New instances of the styles that apply to <paramref name="source"/>
    /// (<see cref="AppliesTo"/>), in the order of <see cref="CreateAll"/>.
    /// </summary>
    /// <param name="source">The coverage source.</param>
    public static IReadOnlyList<WeatherCoverageStyle> CreateFor(WeatherCoverageSource source)
    {
        ArgumentNullException.ThrowIfNull(source);
        return CreateAll().Where(style => style.AppliesTo(source)).ToArray();
    }

    /// <summary>
    /// Builds a colour scheme on <see cref="ValueFieldName"/> from bands whose
    /// colours are tokens of <see cref="WeatherPalette.Palette"/>.
    /// </summary>
    private protected CoverageColorScheme BuildColorScheme(IReadOnlyList<WeatherBand> bands)
    {
        var palette = ActivePalette;
        var colorBands = new ColorBand[bands.Count];
        for (int i = 0; i < bands.Count; i++)
        {
            var band = bands[i];
            colorBands[i] = new ColorBand
            {
                MinValue = band.Minimum,
                MaxValue = band.Maximum,
                Color = palette.Resolve(band.Token),
                Label = band.Label,
            };
        }

        return new CoverageColorScheme { FieldName = ValueFieldName, Bands = colorBands };
    }
}

/// <summary>How a <see cref="WeatherCoverageStyle"/> draws its layer.</summary>
public enum WeatherLayerKind
{
    /// <summary>A colour fill: a <c>GridCoverageSubLayer</c>.</summary>
    Fill,

    /// <summary>Oriented symbols: an <c>ArrowCoverageSubLayer</c>.</summary>
    Symbols,
}

/// <summary>
/// One colour band of a weather fill: a value range in the field's stored
/// unit, the palette token of its colour and a legend label.
/// </summary>
/// <param name="Minimum">The lower bound, inclusive, in the field's stored unit.</param>
/// <param name="Maximum">The upper bound, exclusive, in the field's stored unit.</param>
/// <param name="Token">The colour token in <see cref="WeatherPalette.Palette"/>.</param>
/// <param name="Label">The legend label, in the unit the band is defined in (e.g. knots).</param>
public readonly record struct WeatherBand(float Minimum, float Maximum, string Token, string Label);
