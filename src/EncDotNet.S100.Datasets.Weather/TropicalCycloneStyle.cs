using System.Globalization;
using EncDotNet.S100.Datasets.Pipelines;
using EncDotNet.S100.Datasets.Pipelines.Portrayal;
using EncDotNet.S100.Datasets.TropicalCyclones;
using EncDotNet.S100.Pipelines;
using EncDotNet.S100.Pipelines.Vector;
using EncDotNet.S100.Portrayals.Application;

namespace EncDotNet.S100.Datasets.Weather;

/// <summary>
/// The code-defined drawing of a tropical cyclone advisory
/// (<see cref="TropicalCycloneAdvisory"/>): its forecast cone, wind radii,
/// tracks, forecast points and the storm, all in one plum-grey storm ink
/// (design note <c>docs/design/vector-weather.md</c> §3, V1–V10). Built with
/// the portrayal toolkit (<c>EncDotNet.S100.Portrayals.Application</c>). Not
/// for navigation.
/// </summary>
/// <remarks>
/// <para>
/// <b>Planes (V1).</b> Two sub-layers. The fills, <see cref="AreasLayerKey"/>,
/// go on the On-demand surface plane at <see cref="AreasPriority"/> (10),
/// above the wave fill and under the ENC's line work and soundings: the cone,
/// then the 34, 50 and 64 kt radii. The lines, symbols and labels,
/// <see cref="TrackLayerKey"/>, go on the Other chart overlays plane at
/// <see cref="TrackPriority"/> (95), between the isobars (90) and the
/// observations (100); inside it the radii and cone outlines draw first, then
/// the past track, the forecast track, the forecast points and the storm.
/// </para>
/// <para>
/// <b>Colour (V2, V3; decided Q1).</b> <see cref="WeatherPalette.TropicalCycloneInkToken"/>
/// for every line, symbol and label, with <see cref="WeatherPalette.TropicalCycloneHaloToken"/>
/// under labels and symbols; the cone and radii fills in their own tokens at
/// <see cref="WeatherPalette.TropicalCycloneFillOpacity"/>, so the cone is
/// tinted, not whitened. The part of the cone beyond 72 hours is also
/// stippled (<see cref="StippleFill"/>). No colour is red, amber, magenta,
/// blue or green (§9.3).
/// </para>
/// <para><b>Lines (V4).</b></para>
/// <list type="table">
/// <listheader><term>Line</term><description>Pattern and width</description></listheader>
/// <item><term>Cone outline</term><description>Dashed 1.2 / 0.8 mm, 0.4 mm.</description></item>
/// <item><term>34 kt radius</term><description>Dashed 0.6 / 0.6 mm, 0.4 mm.</description></item>
/// <item><term>50 kt radius</term><description>Solid, 0.4 mm.</description></item>
/// <item><term>64 kt radius</term><description>Solid, 0.8 mm.</description></item>
/// <item><term>Forecast track</term><description>Solid, 0.6 mm.</description></item>
/// <item><term>Past track</term><description>Dotted 0.2 / 0.6 mm, 0.6 mm.</description></item>
/// </list>
/// <para>
/// <b>Symbols (V5–V7).</b> The WMO weather-map glyphs, one per class
/// (<see cref="SymbolFor"/>), generated by <c>tools/GenerateWeatherSymbols</c>
/// into <see cref="WeatherCoverageStyle.Symbols"/>. A northern-hemisphere
/// glyph's arms leave the circle clockwise, top arm to the east, so the
/// storm turns anticlockwise; the southern set is its mirror image. Forecast
/// points draw at the symbols' own size; the storm draws
/// <see cref="StormSymbolScale"/> times larger, inside a ring.
/// </para>
/// <para>
/// <b>Labels (V8–V10).</b> The storm has two lines: the class spelt out, the
/// name, the maximum wind and the pressure (<see cref="StormLabel"/>), then
/// the advisory, its issue time and the motion (<see cref="AdvisoryLabel"/>).
/// The second line is dropped at scales smaller than
/// 1:<see cref="StormDetailScaleMinimum"/>, so the name and intensity stay.
/// Forecast points at 12 hours and every 24 hours, and the last, carry their
/// time and wind (<see cref="ForecastLabel"/>) at 1:<see cref="ForecastTimeScaleMinimum"/>
/// and larger. Times are written in the zone the host passes
/// (<see cref="EncDotNet.S100.Datasets.Pipelines.RenderContext.DisplayTimeZone"/>) and the current culture.
/// </para>
/// </remarks>
public static class TropicalCycloneStyle
{
    /// <summary>The style's name in the tile cache scope.</summary>
    public const string Name = "WeatherTropicalCyclone";

    /// <summary>The style's version: bump it whenever its symbols, palette or rules change.</summary>
    public const int Version = 2;

    /// <summary>The key of the lines, symbols and labels sub-layer, <c>"weather.tc.track"</c>.</summary>
    public const string TrackLayerKey = "weather.tc.track";

    /// <summary>The key of the fills sub-layer, <c>"weather.tc.areas"</c>.</summary>
    public const string AreasLayerKey = "weather.tc.areas";

    /// <summary>
    /// The map-wide switch of the 34, 50 and 64 kt wind radii,
    /// <c>"weather.tc.radii"</c> (V26): a key of
    /// <see cref="EcdisDisplaySettings.LayerVisibility"/>, on by default.
    /// </summary>
    public const string WindRadiiKey = "weather.tc.radii";

    /// <summary>
    /// The map-wide switch of the past track, its line and best-track points,
    /// <c>"weather.tc.pastTrack"</c> (V26), on by default.
    /// </summary>
    public const string PastTrackKey = "weather.tc.pastTrack";

    /// <summary>
    /// The map-wide switch of the time and intensity labels beside forecast
    /// points, <c>"weather.tc.forecastTimes"</c> (V26), on by default.
    /// </summary>
    public const string ForecastTimesKey = "weather.tc.forecastTimes";

    /// <summary>The display switches of tropical cyclones, in the order the Weather section lists them (V26). Each is on by default.</summary>
    public static IReadOnlyList<string> SwitchKeys { get; } = [WindRadiiKey, PastTrackKey, ForecastTimesKey];

    /// <summary>Whether the switch <paramref name="key"/> (one of <see cref="SwitchKeys"/>) is on in <paramref name="display"/>; on when unset.</summary>
    /// <param name="display">The display settings, or <see langword="null"/> for the defaults.</param>
    /// <param name="key">The switch.</param>
    public static bool IsShown(EcdisDisplaySettings? display, string key) =>
        display?.IsLayerVisible(key, defaultVisible: true) ?? true;

    /// <summary>The track sub-layer's order on the Other chart overlays plane: 95, above the isobars and fronts.</summary>
    public const int TrackPriority = 95;

    /// <summary>The fills sub-layer's order on the On-demand surface plane: 10, above the wave fill.</summary>
    public const int AreasPriority = 10;

    /// <summary>The viewing group of every instruction.</summary>
    public const int ViewingGroup = 31040;

    /// <summary>The width of the cone outline and the 34 and 50 kt radius outlines, in millimetres.</summary>
    public const double OutlineWidth = 0.4;

    /// <summary>The width of the 64 kt radius outline, in millimetres.</summary>
    public const double HeavyOutlineWidth = 0.8;

    /// <summary>The width of the forecast and past tracks, in millimetres.</summary>
    public const double TrackWidth = 0.6;

    /// <summary>How much larger than a forecast point the storm is drawn: 6 mm against 3.5 mm (V7).</summary>
    public const double StormSymbolScale = 6.0 / 3.5;

    /// <summary>The largest scale denominator forecast times are drawn at: 20,000,000 (V10).</summary>
    public const double ForecastTimeScaleMinimum = 20_000_000;

    /// <summary>The largest scale denominator the storm label's second line is drawn at: 40,000,000 (V10).</summary>
    public const double StormDetailScaleMinimum = 40_000_000;

    /// <summary>The ring drawn round the storm on a forecast point.</summary>
    public const string RingSymbol = "WXTCRING";

    /// <summary>The dashed ring drawn round a storm position estimated between forecast points (V11).</summary>
    public const string EstimatedRingSymbol = "WXTCRINGEST";

    /// <summary>A best-track point on the past track.</summary>
    public const string PastPointSymbol = "WXTCDOT";

    /// <summary>The pattern symbol, and area fill, that stipples the cone beyond 72 hours.</summary>
    public const string StippleFill = "WXTCSTIPPLE";

    /// <summary>The tile disk-cache content scope of the style (<see cref="ApplicationContentScope"/>).</summary>
    public static string ContentScope { get; } = ApplicationContentScope.For(Name, Version);

    /// <summary>
    /// The class symbols' base names, without the hemisphere suffix: <c>WXTCD</c>
    /// (depression), <c>WXTCS</c> (storm), <c>WXTCH</c> (hurricane or typhoon),
    /// <c>WXTCM</c> (major), <c>WXTCSD</c> and <c>WXTCSS</c> (subtropical) and
    /// <c>WXTCPT</c> (post-tropical, remnant low or disturbance).
    /// </summary>
    public static IReadOnlyList<string> ClassSymbols { get; } = ["WXTCD", "WXTCS", "WXTCH", "WXTCM", "WXTCSD", "WXTCSS", "WXTCPT"];

    /// <summary>
    /// Every symbol the style draws: each of <see cref="ClassSymbols"/> with
    /// <c>N</c> and <c>S</c>, the two rings, the past-track dot and the
    /// stipple, all in <see cref="WeatherCoverageStyle.Symbols"/>.
    /// </summary>
    public static IReadOnlyList<string> AllSymbols { get; } =
        [.. ClassSymbols.SelectMany(name => new[] { name + "N", name + "S" }), RingSymbol, EstimatedRingSymbol, PastPointSymbol, StippleFill];

    private static readonly AreaFill Stipple = new()
    {
        Name = StippleFill,
        PatternSymbol = StippleFill,
        V1X = 2.0,
        V1Y = 0,
        V2X = 0,
        V2Y = 2.0,
    };

    private static readonly TextInstructionStyle StormNameStyle = new()
    {
        FontSize = 12,
        FontColor = WeatherPalette.TropicalCycloneInkToken,
        FontWeight = TextFontWeight.Bold,
        HaloColor = WeatherPalette.TropicalCycloneHaloToken,
        HaloWidth = 0.6,
        HorizontalAlignment = TextHorizontalAlignment.Start,
        VerticalAlignment = TextVerticalAlignment.Bottom,
        OffsetX = 7.0,
        OffsetY = 0.4,
    };

    private static readonly TextInstructionStyle StormDetailStyle = StormNameStyle with
    {
        FontSize = 10.5,
        FontWeight = TextFontWeight.Medium,
        VerticalAlignment = TextVerticalAlignment.Top,
        OffsetY = 1.0,
    };

    private static readonly TextInstructionStyle ForecastStyle = new()
    {
        FontSize = 10,
        FontColor = WeatherPalette.TropicalCycloneInkToken,
        HaloColor = WeatherPalette.TropicalCycloneHaloToken,
        HaloWidth = 0.6,
        HorizontalAlignment = TextHorizontalAlignment.Start,
        VerticalAlignment = TextVerticalAlignment.Center,
        OffsetX = 3.5,
    };

    /// <summary>The stipple area fill, for the <see cref="VectorPortrayalResult.AreaFillProvider"/>.</summary>
    /// <param name="name">The area fill's name.</param>
    /// <returns><see cref="StippleFill"/>'s fill; <see langword="null"/> for any other name.</returns>
    public static AreaFill? ResolveAreaFill(string name) =>
        string.Equals(name, StippleFill, StringComparison.Ordinal) ? Stipple : null;

    /// <summary>
    /// The class symbol of a storm (V5, V6): the base name of its class
    /// (<see cref="ClassSymbols"/>) with <c>N</c> for the northern hemisphere
    /// or <c>S</c> for the southern, where storms turn the other way.
    /// </summary>
    /// <param name="classification">The storm's class.</param>
    /// <param name="saffirSimpsonCategory">Its Saffir–Simpson category, if any; 3 and above is major.</param>
    /// <param name="latitude">The latitude it's drawn at.</param>
    public static string SymbolFor(TropicalCycloneClass classification, int? saffirSimpsonCategory, double latitude)
    {
        string name = classification switch
        {
            TropicalCycloneClass.TropicalDepression => "WXTCD",
            TropicalCycloneClass.TropicalStorm => "WXTCS",
            TropicalCycloneClass.Hurricane or TropicalCycloneClass.Typhoon =>
                saffirSimpsonCategory >= 3 ? "WXTCM" : "WXTCH",
            TropicalCycloneClass.MajorHurricane or TropicalCycloneClass.SuperTyphoon => "WXTCM",
            TropicalCycloneClass.SubtropicalDepression => "WXTCSD",
            TropicalCycloneClass.SubtropicalStorm => "WXTCSS",
            _ => "WXTCPT",
        };
        return name + (latitude < 0 ? "S" : "N");
    }

    /// <summary>
    /// The class spelt out for a label (V8): HURRICANE, TYPHOON, TROPICAL
    /// STORM, TROPICAL DEPRESSION, POST-TROPICAL and so on.
    /// </summary>
    /// <param name="classification">The class.</param>
    public static string ClassWord(TropicalCycloneClass classification) => classification switch
    {
        TropicalCycloneClass.TropicalDepression => "TROPICAL DEPRESSION",
        TropicalCycloneClass.TropicalStorm => "TROPICAL STORM",
        TropicalCycloneClass.Hurricane or TropicalCycloneClass.MajorHurricane => "HURRICANE",
        TropicalCycloneClass.Typhoon => "TYPHOON",
        TropicalCycloneClass.SuperTyphoon => "SUPER TYPHOON",
        TropicalCycloneClass.SubtropicalDepression => "SUBTROPICAL DEPRESSION",
        TropicalCycloneClass.SubtropicalStorm => "SUBTROPICAL STORM",
        TropicalCycloneClass.PostTropical or TropicalCycloneClass.Extratropical => "POST-TROPICAL",
        TropicalCycloneClass.Low => "LOW",
        TropicalCycloneClass.Disturbance => "DISTURBANCE",
        TropicalCycloneClass.TropicalWave => "TROPICAL WAVE",
        TropicalCycloneClass.PotentialTropicalCyclone => "POTENTIAL TROPICAL CYCLONE",
        _ => "STORM",
    };

    /// <summary>
    /// The class for the pick card's pill: "Category 4" for a hurricane or
    /// typhoon with a Saffir–Simpson category, otherwise the class in
    /// sentence case, such as "Tropical storm".
    /// </summary>
    /// <param name="classification">The class.</param>
    /// <param name="saffirSimpsonCategory">The category, if any.</param>
    public static string ClassName(TropicalCycloneClass classification, int? saffirSimpsonCategory)
    {
        if (saffirSimpsonCategory is >= 1 and <= 5
            && classification is TropicalCycloneClass.Hurricane or TropicalCycloneClass.MajorHurricane
                or TropicalCycloneClass.Typhoon or TropicalCycloneClass.SuperTyphoon)
        {
            return string.Create(CultureInfo.InvariantCulture, $"Category {saffirSimpsonCategory}");
        }

        var word = ClassWord(classification).ToLowerInvariant();
        return char.ToUpperInvariant(word[0]) + word[1..];
    }

    /// <summary>
    /// The first line of the storm's label (V8): <c>HURRICANE IAN · 105 kt · 952 hPa</c>,
    /// without the pressure when the advisory has none.
    /// </summary>
    /// <param name="storm">The storm.</param>
    /// <param name="point">The forecast point the storm is drawn at.</param>
    public static string StormLabel(TropicalCycloneStorm storm, TropicalCycloneForecastPoint point)
    {
        ArgumentNullException.ThrowIfNull(storm);
        ArgumentNullException.ThrowIfNull(point);
        var parts = new List<string>(3)
        {
            string.IsNullOrWhiteSpace(storm.Name)
                ? ClassWord(point.Classification)
                : $"{ClassWord(point.Classification)} {storm.Name.Trim().ToUpperInvariant()}",
        };
        if (point.MaxWindKnots is { } wind)
            parts.Add(string.Create(CultureInfo.InvariantCulture, $"{wind} kt"));
        if (point.PressureHectopascals is { } pressure)
            parts.Add(string.Create(CultureInfo.InvariantCulture, $"{pressure} hPa"));
        return string.Join(" · ", parts);
    }

    /// <summary>
    /// The second line of the storm's label (V8): <c>Adv 20 · issued Tue 11:00 PM · NNW 9 kt</c>,
    /// without the motion when the advisory has none.
    /// </summary>
    /// <param name="advisory">The advisory.</param>
    /// <param name="point">The forecast point the storm is drawn at.</param>
    /// <param name="zone">The zone the time is written in.</param>
    /// <param name="culture">The culture the time is written in.</param>
    public static string AdvisoryLabel(TropicalCycloneAdvisory advisory, TropicalCycloneForecastPoint point, TimeZoneInfo zone, CultureInfo culture)
    {
        ArgumentNullException.ThrowIfNull(advisory);
        ArgumentNullException.ThrowIfNull(point);
        var text = $"Adv {advisory.Advisory} · issued {ShortTime(advisory.IssueTime.UtcDateTime, zone, culture)}";
        if (Motion(point) is { } motion)
            text += " · " + motion;
        return text;
    }

    /// <summary>
    /// The second line of a stale storm's label (V29, §7):
    /// <c>Adv 17 · 9 h old · newer advisory likely</c>. The storm itself isn't faded.
    /// </summary>
    /// <param name="advisory">The advisory.</param>
    /// <param name="age">How old the advisory is.</param>
    public static string StaleAdvisoryLabel(TropicalCycloneAdvisory advisory, TimeSpan age)
    {
        ArgumentNullException.ThrowIfNull(advisory);
        return string.Create(CultureInfo.InvariantCulture, $"Adv {advisory.Advisory} · {Math.Round(age.TotalHours):0} h old · newer advisory likely");
    }

    /// <summary>
    /// The second line of a final advisory's storm label (§7):
    /// <c>Final advisory issued Wed 9:00 AM</c>.
    /// </summary>
    /// <param name="advisory">The advisory.</param>
    /// <param name="zone">The zone the time is written in.</param>
    /// <param name="culture">The culture the time is written in.</param>
    public static string FinalAdvisoryLabel(TropicalCycloneAdvisory advisory, TimeZoneInfo zone, CultureInfo culture)
    {
        ArgumentNullException.ThrowIfNull(advisory);
        return $"Final advisory issued {ShortTime(advisory.IssueTime.UtcDateTime, zone, culture)}";
    }

    /// <summary>The label beside a forecast point (V9): <c>Thu 6:00 AM · 110 kt</c>.</summary>
    /// <param name="point">The forecast point.</param>
    /// <param name="zone">The zone the time is written in.</param>
    /// <param name="culture">The culture the time is written in.</param>
    public static string ForecastLabel(TropicalCycloneForecastPoint point, TimeZoneInfo zone, CultureInfo culture)
    {
        ArgumentNullException.ThrowIfNull(point);
        var time = ShortTime(point.ValidTime, zone, culture);
        return point.MaxWindKnots is { } wind
            ? string.Create(CultureInfo.InvariantCulture, $"{time} · {wind} kt")
            : time;
    }

    /// <summary>
    /// The storm's motion, <c>NNW 9 kt</c>, on the 16-point compass;
    /// "stationary" under a knot; <see langword="null"/> when the advisory
    /// doesn't give it.
    /// </summary>
    /// <param name="point">The forecast point.</param>
    public static string? Motion(TropicalCycloneForecastPoint point)
    {
        ArgumentNullException.ThrowIfNull(point);
        if (point.MotionSpeedKnots is not { } speed)
            return null;
        if (speed < 1)
            return "stationary";
        if (point.MotionDirectionDegrees is not { } direction)
            return string.Create(CultureInfo.InvariantCulture, $"{speed:0} kt");
        return string.Create(CultureInfo.InvariantCulture, $"{CompassPoint(direction)} {speed:0} kt");
    }

    /// <summary>The 16-point compass name of a direction in degrees: N, NNE, NE … NNW.</summary>
    /// <param name="degrees">The direction, clockwise from true north.</param>
    public static string CompassPoint(double degrees)
    {
        string[] points = ["N", "NNE", "NE", "ENE", "E", "ESE", "SE", "SSE", "S", "SSW", "SW", "WSW", "W", "WNW", "NW", "NNW"];
        int index = (int)Math.Round(((degrees % 360) + 360) % 360 / 22.5) % 16;
        return points[index];
    }

    /// <summary>Whether a forecast point carries a time label (V9): at 12 hours, every 24 hours, and the last.</summary>
    /// <param name="point">The forecast point.</param>
    /// <param name="isLast">Whether it's the advisory's last.</param>
    public static bool IsLabelled(TropicalCycloneForecastPoint point, bool isLast)
    {
        ArgumentNullException.ThrowIfNull(point);
        return point.Tau > 0 && (isLast || point.Tau == 12 || point.Tau % 24 == 0);
    }

    /// <summary>
    /// The fill of a part of the cone, in <paramref name="palette"/>: the cone
    /// tint, and for days 4–5 the stipple over it.
    /// </summary>
    /// <param name="featureReference">The part's feature id, a surface.</param>
    /// <param name="daysFourToFive">Whether it's the part beyond 72 hours.</param>
    /// <param name="palette">The palette, which sets the opacity.</param>
    public static IReadOnlyList<DrawingInstruction> BuildConeFill(string featureReference, bool daysFourToFive, PaletteType palette)
    {
        var builder = Areas(drawingPriority: 1);
        var tint = builder.Area(featureReference, WeatherPalette.TropicalCycloneConeToken, Transparency(WeatherPalette.TropicalCycloneConeToken, palette));
        return daysFourToFive ? [tint, builder.AreaPattern(featureReference, StippleFill)] : [tint];
    }

    /// <summary>The dashed outline of the whole cone (V4).</summary>
    /// <param name="featureReference">The cone's feature id, a surface.</param>
    public static DrawingInstruction BuildConeOutline(string featureReference) =>
        Track(drawingPriority: 1).Line(featureReference, WeatherPalette.TropicalCycloneInkToken, OutlineWidth, 1.2, 0.8);

    /// <summary>The fill of a wind radius, in <paramref name="palette"/> (V2): the 64 kt core over the 50 kt over the 34 kt.</summary>
    /// <param name="featureReference">The radius's feature id, a surface.</param>
    /// <param name="thresholdKnots">34, 50 or 64.</param>
    /// <param name="palette">The palette, which sets the opacity.</param>
    public static DrawingInstruction BuildRadiusFill(string featureReference, int thresholdKnots, PaletteType palette)
    {
        var token = RadiusToken(thresholdKnots);
        return Areas(drawingPriority: 2 + RadiusRank(thresholdKnots)).Area(featureReference, token, Transparency(token, palette));
    }

    /// <summary>The outline of a wind radius (V4): 34 kt dashed, 50 kt solid, 64 kt heavy.</summary>
    /// <param name="featureReference">The radius's feature id, a surface.</param>
    /// <param name="thresholdKnots">34, 50 or 64.</param>
    public static DrawingInstruction BuildRadiusOutline(string featureReference, int thresholdKnots)
    {
        var builder = Track(drawingPriority: 2);
        return thresholdKnots switch
        {
            34 => builder.Line(featureReference, WeatherPalette.TropicalCycloneInkToken, OutlineWidth, 0.6, 0.6),
            50 => builder.Line(featureReference, WeatherPalette.TropicalCycloneInkToken, OutlineWidth),
            64 => builder.Line(featureReference, WeatherPalette.TropicalCycloneInkToken, HeavyOutlineWidth),
            _ => throw new ArgumentOutOfRangeException(nameof(thresholdKnots), thresholdKnots, "A wind radius is 34, 50 or 64 kt."),
        };
    }

    /// <summary>The solid forecast track (V4).</summary>
    /// <param name="featureReference">The track's feature id, a curve.</param>
    public static DrawingInstruction BuildForecastTrack(string featureReference) =>
        Track(drawingPriority: 4).Line(featureReference, WeatherPalette.TropicalCycloneInkToken, TrackWidth);

    /// <summary>The dotted past track (V4).</summary>
    /// <param name="featureReference">The track's feature id, a curve.</param>
    public static DrawingInstruction BuildPastTrack(string featureReference) =>
        Track(drawingPriority: 3).Line(featureReference, WeatherPalette.TropicalCycloneInkToken, TrackWidth, 0.2, 0.6);

    /// <summary>A best-track point on the past track.</summary>
    /// <param name="featureReference">The point's feature id.</param>
    public static DrawingInstruction BuildPastPoint(string featureReference) =>
        Track(drawingPriority: 3).Point(featureReference, PastPointSymbol);

    /// <summary>A forecast point: its class symbol, and its time and wind when it carries a label (V7, V9).</summary>
    /// <param name="featureReference">The point's feature id.</param>
    /// <param name="symbol">Its class symbol (<see cref="SymbolFor"/>).</param>
    /// <param name="label">Its label (<see cref="ForecastLabel"/>), or <see langword="null"/> for none.</param>
    public static IReadOnlyList<DrawingInstruction> BuildForecastPoint(string featureReference, string symbol, string? label)
    {
        var builder = Track(drawingPriority: 5);
        var point = builder.Point(featureReference, symbol);
        return label is null
            ? [point]
            : [point, (builder with { ScaleMinimum = ForecastTimeScaleMinimum }).Text(featureReference, label, ForecastStyle)];
    }

    /// <summary>
    /// The storm (V7, V8): its class symbol, <see cref="StormSymbolScale"/>
    /// times larger, in a ring, solid on a forecast point and dashed when
    /// estimated between points, and its two-line label.
    /// </summary>
    /// <param name="featureReference">The storm's feature id, a point.</param>
    /// <param name="symbol">Its class symbol (<see cref="SymbolFor"/>).</param>
    /// <param name="estimated">Whether the position is estimated between forecast points.</param>
    /// <param name="name">The label's first line (<see cref="StormLabel"/>).</param>
    /// <param name="detail">The label's second line (<see cref="AdvisoryLabel"/>).</param>
    public static IReadOnlyList<DrawingInstruction> BuildStorm(string featureReference, string symbol, bool estimated, string name, string detail)
    {
        var builder = Track(drawingPriority: 6);
        return
        [
            builder.Point(featureReference, estimated ? EstimatedRingSymbol : RingSymbol, symbolScale: StormSymbolScale),
            builder.Point(featureReference, symbol, symbolScale: StormSymbolScale),
            builder.Text(featureReference, name, StormNameStyle),
            (builder with { ScaleMinimum = StormDetailScaleMinimum }).Text(featureReference, detail, StormDetailStyle),
        ];
    }

    /// <summary>
    /// The legend under the track entry, in the given palette (V25): one
    /// symbol per class, the southern-hemisphere mirror, the forecast track
    /// and the past track.
    /// </summary>
    /// <param name="palette">The palette the glyphs are drawn in.</param>
    public static IReadOnlyList<LegendEntry> BuildTrackLegend(PaletteType palette)
    {
        var legend = new LegendBuilder(WeatherPalette.Palette, palette, WeatherCoverageStyle.Symbols.Provider);
        return
        [
            legend.Symbol("WXTCDN", "Tropical depression"),
            legend.Symbol("WXTCSN", "Tropical storm"),
            legend.Symbol("WXTCHN", "Hurricane, typhoon"),
            legend.Symbol("WXTCMN", "Major (cat. 3+)"),
            legend.Symbol("WXTCPTN", "Post-tropical, low"),
            legend.Symbol("WXTCHS", "Southern hemisphere"),
            legend.Line(WeatherPalette.TropicalCycloneInkToken, TrackWidth, "Forecast track"),
            legend.Line(WeatherPalette.TropicalCycloneInkToken, TrackWidth, "Past track", 0.2, 0.6),
        ];
    }

    /// <summary>
    /// The legend under the areas entry, in the given palette (V25): the cone
    /// for days 1–3 and 4–5, and the 34, 50 and 64 kt areas, each with its
    /// outline.
    /// </summary>
    /// <param name="palette">The palette the swatches are drawn in.</param>
    public static IReadOnlyList<LegendEntry> BuildAreasLegend(PaletteType palette)
    {
        var legend = new LegendBuilder(WeatherPalette.Palette, palette, WeatherCoverageStyle.Symbols.Provider);
        const string ink = WeatherPalette.TropicalCycloneInkToken;
        // The swatches are small, so their tint is doubled to read as the map does.
        LegendEntry Area(string token, string label, LegendLineSample outline) =>
            legend.Area(token, label, outline, 1 - Math.Min(1, 2 * WeatherPalette.TropicalCycloneFillOpacity(token, palette)));
        return
        [
            Area(WeatherPalette.TropicalCycloneConeToken, "Cone, days 1–3", legend.Sample(ink, OutlineWidth, 1.2, 0.8)),
            Area(WeatherPalette.TropicalCycloneConeToken, "Cone, days 4–5 (stippled)", legend.Sample(ink, OutlineWidth, 0.4, 0.4)),
            Area(WeatherPalette.TropicalCyclone34Token, "34 kt winds", legend.Sample(ink, OutlineWidth, 0.6, 0.6)),
            Area(WeatherPalette.TropicalCyclone50Token, "50 kt winds", legend.Sample(ink, OutlineWidth)),
            Area(WeatherPalette.TropicalCyclone64Token, "64 kt winds", legend.Sample(ink, HeavyOutlineWidth)),
        ];
    }

    /// <summary>The fill token of a wind radius: <see cref="WeatherPalette.TropicalCyclone34Token"/>, 50 or 64.</summary>
    /// <param name="thresholdKnots">34, 50 or 64.</param>
    public static string RadiusToken(int thresholdKnots) => thresholdKnots switch
    {
        34 => WeatherPalette.TropicalCyclone34Token,
        50 => WeatherPalette.TropicalCyclone50Token,
        64 => WeatherPalette.TropicalCyclone64Token,
        _ => throw new ArgumentOutOfRangeException(nameof(thresholdKnots), thresholdKnots, "A wind radius is 34, 50 or 64 kt."),
    };

    // The time of a label: the weekday and the culture's short time, in the zone.
    private static string ShortTime(DateTime utc, TimeZoneInfo zone, CultureInfo culture)
    {
        ArgumentNullException.ThrowIfNull(zone);
        ArgumentNullException.ThrowIfNull(culture);
        var local = TimeZoneInfo.ConvertTimeFromUtc(DateTime.SpecifyKind(utc, DateTimeKind.Utc), zone);
        return local.ToString("ddd ", culture) + local.ToString("t", culture);
    }

    private static int RadiusRank(int thresholdKnots) => thresholdKnots switch
    {
        34 => 0,
        50 => 1,
        64 => 2,
        _ => throw new ArgumentOutOfRangeException(nameof(thresholdKnots), thresholdKnots, "A wind radius is 34, 50 or 64 kt."),
    };

    private static double Transparency(string token, PaletteType palette) =>
        1 - WeatherPalette.TropicalCycloneFillOpacity(token, palette);

    private static InstructionBuilder Areas(int drawingPriority) =>
        new() { ViewingGroup = ViewingGroup, DrawingPriority = drawingPriority };

    // The track sub-layer's priorities sit above the fills' (1-4), so the
    // two sub-layers also order right when drawn as one list (headless).
    private static InstructionBuilder Track(int drawingPriority) =>
        new() { ViewingGroup = ViewingGroup, DrawingPriority = 10 + drawingPriority };
